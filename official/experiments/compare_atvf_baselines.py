"""Join ATVF runs with existing baseline CSVs and compute per-horizon ranks.

Run from official/:
  python experiments/compare_atvf_baselines.py --atvf results/atvf_summary.csv
The script reads baseline CSVs from the repository's existing experiments and
exchange_rate result folders. It never invents missing model scores.
"""
import argparse
from pathlib import Path
import pandas as pd


def load_baselines(repo_root: Path):
    candidates = [
        (repo_root.parent / "experiments/results/ETTh1_baselines_comparison.csv", "ETTh1"),
        (repo_root.parent / "exchange_rate/results/results_exchange_rate.csv", "exchange_rate"),
    ]
    frames = []
    for path, dataset in candidates:
        if not path.exists():
            print(f"[skip] Baseline CSV not found: {path}")
            continue
        frame = pd.read_csv(path, skipinitialspace=True)
        frame.columns = [str(c).strip().lower() for c in frame.columns]
        required = {"model", "pred_len", "mse", "mae"}
        if not required.issubset(frame.columns):
            print(f"[skip] Unexpected columns in {path}: {list(frame.columns)}")
            continue
        frame["model"] = frame["model"].astype(str).str.strip()
        frame["dataset"] = dataset
        frames.append(frame[["model", "dataset", "pred_len", "mse", "mae"]])
    return frames


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--atvf", default="results/atvf_summary.csv")
    parser.add_argument("--output", default="results/atvf_vs_baselines.csv")
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    atvf_path = Path(args.atvf)
    if not atvf_path.is_absolute():
        atvf_path = root / atvf_path
    if not atvf_path.exists():
        raise FileNotFoundError(f"ATVF results not found: {atvf_path}")

    atvf = pd.read_csv(atvf_path)
    if not {"dataset", "pred_len", "mse", "mae"}.issubset(atvf.columns):
        raise ValueError("ATVF CSV must be generated by collect_atvf_results.py.")
    atvf = atvf[atvf["dataset"].isin(["ETTh1", "exchange_rate"])].copy()
    if atvf.empty:
        raise ValueError("No ATVF rows with recognized dataset/horizon metadata.")

    # Average seeds for each dataset and prediction horizon.
    atvf = atvf.groupby(["dataset", "pred_len"], as_index=False)[["mse", "mae"]].mean()
    atvf["model"] = "ATVF"

    frames = load_baselines(root)
    frames.append(atvf[["model", "dataset", "pred_len", "mse", "mae"]])
    combined = pd.concat(frames, ignore_index=True)
    combined["mse_rank"] = combined.groupby(["dataset", "pred_len"])["mse"].rank(method="min")
    combined["mae_rank"] = combined.groupby(["dataset", "pred_len"])["mae"].rank(method="min")
    output = Path(args.output)
    if not output.is_absolute():
        output = root / output
    output.parent.mkdir(parents=True, exist_ok=True)
    combined.sort_values(["dataset", "pred_len", "mse_rank"]).to_csv(output, index=False)
    print(f"Saved comparison table: {output}")
    print(combined.sort_values(["dataset", "pred_len", "mse_rank"]).to_string(index=False))


if __name__ == "__main__":
    main()
